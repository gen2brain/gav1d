#define SETUP                   \
	MOV tmp+0(FP), X10;     \
	MOV lanes+8(FP), X22;   \
	MOV stride+16(FP), X23; \
	MOVW lo+24(FP), X28;    \
	MOVW hi+28(FP), X29;    \
	SLLI $2, X23, X23;      \
	KONST

// LOADN and STOREN walk the rows, so the butterfly never addresses memory.
#define LD2(V0, V1)  \
	VLE32V (X24), V0; \
	ADD    X23, X24;  \
	VLE32V (X24), V1; \
	ADD    X23, X24

#define ST2(V0, V1)  \
	VSE32V V0, (X24); \
	ADD    X23, X24;  \
	VSE32V V1, (X24); \
	ADD    X23, X24

// ODD8 is the four-point odd half, from A1, A3, A5 and A7, leaving t4, t5, t6
// and t7 in T4, T5, T6 and T7.
#define ODD8(A1, A3, A5, A7, T4, T5, T6, T7, S) \
	MACA(T4, A1, X9, A7, X11, $12, S); \
	VSUBVV A7, T4, T4;                 \
	MACS(T5, A5, X12, A3, X13, $11, S); \
	MACA(T6, A5, X13, A3, X12, $11, S); \
	MACS(T7, A7, X9, A1, X11, $12, S); \
	VADDVV A1, T7, T7;                 \
	VADDVV T5, T4, A1;                 \
	CLIP(A1);                          \
	VSUBVV T5, T4, A3;                 \
	CLIP(A3);                          \
	VADDVV T6, T7, A7;                 \
	CLIP(A7);                          \
	VSUBVV T6, T7, A5;                 \
	CLIP(A5);                          \
	R181(T5, A5, A3, SUBV);            \
	R181(T6, A5, A3, ADDV);            \
	VMVVV A1, T4;                      \
	VMVVV A7, T7

// BFLY writes the pair one butterfly produces, leaving the sum in A.
#define BFLY(A, B, S) \
	VSUBVV B, A, S; \
	CLIP(S);        \
	VADDVV B, A, A; \
	CLIP(A);        \
	VMVVV  S, B

