	MACA(Y5, Y3, K1567, Y9, K312, K2048, 12, Y13)
	VPSUBD Y9, Y5, Y5
	MACS(Y6, Y9, K1567, Y3, K312, K2048, 12, Y13)
	VPADDD Y3, Y6, Y6
	MACS(Y7, Y2, K312, Y10, K1567, K2048, 12, Y13)
	VPSUBD Y2, Y7, Y7
	MACA(Y12, Y2, K1567, Y10, K312, K2048, 12, Y13)
