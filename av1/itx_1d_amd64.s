	VMOVDQU (R8)(R9*1), Y9
	MACS(Y1, Y8, K1583, Y9, K1299, K1024, 11, Y10)
	MACA(Y6, Y8, K1299, Y9, K1583, K1024, 11, Y10)

	VMOVDQU (R8)(DX*1), Y8
	VMOVDQU (R10)(R9*1), Y9
	MACA(Y2, Y8, K1931, Y9, K484, K2048, 12, Y10)
	VPSUBD Y9, Y2, Y2
	MACS(Y5, Y9, K1931, Y8, K484, K2048, 12, Y10)
	VPADDD Y8, Y5, Y5

	VMOVDQU (R11)(DX*1), Y8
	VMOVDQU (SI)(R9*1), Y9
	VPMULLD K176, Y8, Y3
	VPMULLD K1189, Y9, Y10
	VPADDD  Y10, Y3, Y3
	VPSUBD  Y3, Y11, Y3
	VPADDD  K2048, Y3, Y3
	VPSRAD  $12, Y3, Y3
	VPADDD  Y8, Y3, Y3
	MACS(Y4, Y8, K1189, Y9, K176, K2048, 12, Y10)
	VPADDD Y9, Y4, Y4

	VPADDD Y1, Y0, Y8
	CLIP(Y8)
	VPSUBD Y1, Y0, Y9
	CLIP(Y9)
	VPSUBD Y2, Y3, Y10
	CLIP(Y10)
	VPADDD Y2, Y3, Y0
	CLIP(Y0)
	VPADDD Y5, Y4, Y1
	CLIP(Y1)
	VPSUBD Y5, Y4, Y2
	CLIP(Y2)
	VPSUBD Y6, Y7, Y3
	CLIP(Y3)
