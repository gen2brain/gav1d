// MACA is (A*CA + B*CB + RND) >> SH, MACS the same with the second term
// subtracted. The scalar path rounds once, after the sum.
#define MACA(D, A, CA, B, CB, RND, SH, T) \
	VPMULLD CA, A, D;  \
	VPMULLD CB, B, T;  \
	VPADDD  T, D, D;   \
	VPADDD  RND, D, D; \
	VPSRAD  $SH, D, D

#define MACS(D, A, CA, B, CB, RND, SH, T) \
	VPMULLD CA, A, D;  \
	VPMULLD CB, B, T;  \
	VPSUBD  T, D, D;   \
	VPADDD  RND, D, D; \
	VPSRAD  $SH, D, D

// R181 is ((A OP B)*181 + 128) >> 8, the half-turn butterfly.
#define R181(D, A, B, OP) \
	OP      B, A, D;  \
	VPMULLD K181, D, D; \
	VPADDD  K128, D, D; \
	VPSRAD  $8, D, D

#define CLIP(V)          \
	VPMAXSD Y14, V, V; \
	VPMINSD Y15, V, V

// BFLY writes the two outputs a butterfly pair produces.
#define BFLY(LO, HI, A, B, T) \
	VPADDD B, A, T;       \
	CLIP(T);              \
	VMOVDQU T, LO;        \
	VPSUBD B, A, T;       \
	CLIP(T);              \
	VMOVDQU T, HI

// SETUP takes the lane count, the tap stride and the clip bounds.
#define SETUP                     \
	MOVQ tmp+0(FP), SI;       \
	MOVQ lanes+8(FP), BX;     \
	MOVQ stride+16(FP), DX;   \
	MOVL lo+24(FP), AX;       \
	VMOVD AX, X14;            \
	VPBROADCASTD X14, Y14;    \
	MOVL hi+28(FP), AX;       \
	VMOVD AX, X15;            \
	VPBROADCASTD X15, Y15;    \
	SHLQ $2, DX;              \
	LEAQ (DX)(DX*2), R9

// DCT4 is the four-point core, in0..in3 in A0..A3 and the results back in them.
#define DCT4(A0, A1, A2, A3, T0, T1, T2) \
	R181(T0, A0, A2, VPADDD); \
	R181(T1, A0, A2, VPSUBD); \
	MACA(T2, A1, K1567, A3, K312, K2048, 12, A0); \
	VPSUBD A3, T2, T2;        \
	MACS(A0, A3, K1567, A1, K312, K2048, 12, A2); \
	VPADDD A1, A0, A3;        \
	VPADDD A3, T0, A0;        \
	CLIP(A0);                 \
	VPADDD T2, T1, A1;        \
	CLIP(A1);                 \
	VPSUBD T2, T1, A2;        \
	CLIP(A2);                 \
	VPSUBD A3, T0, A3;        \
	CLIP(A3)

// func itxColDct4AVX2(tmp *int32, lanes, stride int, lo, hi int32)
TEXT ·itxColDct4AVX2(SB), NOSPLIT, $0-32
	SETUP

col4:
	VMOVDQU (SI), Y0
	VMOVDQU (SI)(DX*1), Y1
	VMOVDQU (SI)(DX*2), Y2
	VMOVDQU (SI)(R9*1), Y3
	DCT4(Y0, Y1, Y2, Y3, Y4, Y5, Y6)
	VMOVDQU Y0, (SI)
	VMOVDQU Y1, (SI)(DX*1)
	VMOVDQU Y2, (SI)(DX*2)
	VMOVDQU Y3, (SI)(R9*1)

	ADDQ $32, SI
	SUBQ $8, BX
	JNZ  col4

	VZEROUPPER
	RET

// func itxColDct8AVX2(tmp *int32, lanes, stride int, lo, hi int32)
TEXT ·itxColDct8AVX2(SB), NOSPLIT, $0-32
	SETUP

col8:
	LEAQ (SI)(DX*4), R8

	VMOVDQU (SI), Y0
	VMOVDQU (SI)(DX*2), Y1
	VMOVDQU (R8), Y2
	VMOVDQU (R8)(DX*2), Y3
	DCT4(Y0, Y1, Y2, Y3, Y4, Y5, Y6)

	VMOVDQU (SI)(DX*1), Y4
	VMOVDQU (SI)(R9*1), Y5
	VMOVDQU (R8)(DX*1), Y6
	VMOVDQU (R8)(R9*1), Y7

	MACA(Y8, Y4, K799, Y7, K79, K2048, 12, Y13)
	VPSUBD Y7, Y8, Y8
	MACS(Y9, Y6, K1703, Y5, K1138, K1024, 11, Y13)
	MACA(Y10, Y6, K1138, Y5, K1703, K1024, 11, Y13)
	MACS(Y11, Y7, K799, Y4, K79, K2048, 12, Y13)
	VPADDD Y4, Y11, Y11

	VPADDD Y9, Y8, Y4
	CLIP(Y4)
	VPSUBD Y9, Y8, Y5
	CLIP(Y5)
	VPADDD Y10, Y11, Y7
	CLIP(Y7)
	VPSUBD Y10, Y11, Y6
	CLIP(Y6)

	R181(Y8, Y6, Y5, VPSUBD)
	R181(Y9, Y6, Y5, VPADDD)

	BFLY((SI), (R8)(R9*1), Y0, Y7, Y13)
	BFLY((SI)(DX*1), (R8)(DX*2), Y1, Y9, Y13)
	BFLY((SI)(DX*2), (R8)(DX*1), Y2, Y8, Y13)
	BFLY((SI)(R9*1), (R8), Y3, Y4, Y13)

	ADDQ $32, SI
	SUBQ $8, BX
	JNZ  col8

	VZEROUPPER
	RET

