	ABSV(V0, V16)
	ABSV(V1, V16)
	ABSV(V2, V16)
	ABSV(V3, V16)
	ABSV(V4, V16)
	ABSV(V5, V16)
	ABSV(V6, V16)
	ABSV(V7, V16)
	VADDVV    V1, V0, V0
	VADDVV    V3, V2, V2
	VADDVV    V5, V4, V4
	VADDVV    V7, V6, V6
	VADDVV    V2, V0, V0
	VADDVV    V6, V4, V4
	VADDVV    V4, V0, V0
	VMVVI     $0, V8
	VREDSUMVS V8, V0, V8
	VMVXS     V8, X6
	ADDW      $4, X6, X6
	SRAW      $3, X6, X6
	MOVW      X6, ret+16(FP)
	RET

#define RSR(v) \
	VADDVX X21, v, v; \
	VSRAVI $13, v, v

#define FDCT4R(i0, i1, i2, i3) \
	VADDVV i3, i0, V10; \
	VADDVV i2, i1, V11; \
	VSUBVV i2, i1, V12; \
	VSUBVV i3, i0, V13; \
	VADDVV V11, V10, V14; \
	VSUBVV V11, V10, V15; \
	VMULVX X17, V14, i0; \
	RSR(i0); \
	VMULVX X17, V15, i2; \
	RSR(i2); \
	VMULVX X18, V12, V16; \
	VMULVX X19, V13, V17; \
	VADDVV V17, V16, i1; \
	RSR(i1); \
	VMULVX X18, V13, V16; \
	VMULVX X19, V12, V17; \
	VSUBVV V17, V16, i3; \
	RSR(i3)

#define FADST4R(i0, i1, i2, i3) \
	VMULVX X17, i0, V10; \
	VMULVX X19, i1, V11; \
	VADDVV V11, V10, V10; \
	VMULVX X20, i3, V11; \
	VADDVV V11, V10, V10; \
	VMULVX X20, i0, V11; \
	VMULVX X17, i1, V12; \
	VSUBVV V12, V11, V11; \
	VMULVX X19, i3, V12; \
	VADDVV V12, V11, V11; \
	VMULVX X18, i2, V12; \
	VADDVV i1, i0, V13; \
	VSUBVV i3, V13, V13; \
	VMULVX X18, V13, V13; \
	VADDVV V12, V10, V14; \
	RSR(V14); \
	RSR(V13); \
	VSUBVV V12, V11, V15; \
	RSR(V15); \
	VSUBVV V10, V11, V16; \
	VADDVV V12, V16, V16; \
	RSR(V16); \
	VMVVV V14, i0; \
	VMVVV V13, i1; \
	VMVVV V15, i2; \
	VMVVV V16, i3

// fwdTxfm4x4RVV is the 4x4 forward transform for the four non-flipping
// DCT/ADST combinations. cos_bit is 13 at this size, so the constants are
// scalars and every intermediate fits int32 for 8-bit input.
TEXT ·fwdTxfm4x4RVV(SB), NOSPLIT, $64-40
	MOV  res+0(FP), X10
	MOV  src+8(FP), X11
	MOV  srcStride+16(FP), X12
	SLLI $2, X12, X12
	MOV  $4, X13
	VSETVLI X13, E32, M1, TA, MA, X5
	MOV  $4096, X21

	VLE32V (X11), V0
	ADD    X12, X11, X14
	VLE32V (X14), V1
	ADD    X12, X14, X14
	VLE32V (X14), V2
	ADD    X12, X14, X14
	VLE32V (X14), V3
	VSLLVI $2, V0, V0
	VSLLVI $2, V1, V1
	VSLLVI $2, V2, V2
	VSLLVI $2, V3, V3

	MOV colAdst+24(FP), X22
	BNEZ X22, coladstr
	MOV $5793, X17
	MOV $3135, X18
	MOV $7568, X19
	FDCT4R(V0, V1, V2, V3)
	JMP colfinr

coladstr:
	MOV $2642, X17
	MOV $6689, X18
	MOV $4964, X19
	MOV $7606, X20
	FADST4R(V0, V1, V2, V3)

colfinr:
	MOV    $scratch-64(SP), X14
	VSE32V V0, (X14)
	ADD    $16, X14, X15
	VSE32V V1, (X15)
	ADD    $16, X15, X15
	VSE32V V2, (X15)
	ADD    $16, X15, X15
	VSE32V V3, (X15)
	MOV     $16, X16
	VLSE32V (X14), X16, V0
	ADD     $4, X14, X15
	VLSE32V (X15), X16, V1
	ADD     $4, X15, X15
	VLSE32V (X15), X16, V2
	ADD     $4, X15, X15
	VLSE32V (X15), X16, V3

	MOV rowAdst+32(FP), X22
	BNEZ X22, rowadstr
	MOV $5793, X17
	MOV $3135, X18
	MOV $7568, X19
	FDCT4R(V0, V1, V2, V3)
	JMP storer

rowadstr:
	MOV $2642, X17
	MOV $6689, X18
	MOV $4964, X19
	MOV $7606, X20
	FADST4R(V0, V1, V2, V3)

storer:
	VSE32V V0, (X10)
	ADD    $16, X10, X15
	VSE32V V1, (X15)
	ADD    $16, X15, X15
	VSE32V V2, (X15)
	ADD    $16, X15, X15
	VSE32V V3, (X15)
	RET

// FDCT8R is an eight point DCT across eight vectors. Constants are scalars:
// X17 cospi32, X18 cospi48, X19 cospi16, X20 cospi56, X23 cospi24, X24 cospi40,
// X25 cospi8, X21 the rounding term. The final permutation is folded into the
// destination registers, so the inputs come back in frequency order.
#define FDCT8R(i0, i1, i2, i3, i4, i5, i6, i7) \
	VADDVV i7, i0, V10; \
	VADDVV i6, i1, V11; \
	VADDVV i5, i2, V12; \
	VADDVV i4, i3, V13; \
	VSUBVV i4, i3, V14; \
	VSUBVV i5, i2, V15; \
	VSUBVV i6, i1, V16; \
	VSUBVV i7, i0, V17; \
	VADDVV V13, V10, V18; \
	VADDVV V12, V11, V19; \
	VSUBVV V12, V11, V20; \
	VSUBVV V13, V10, V21; \
	VSUBVV V15, V16, V22; \
	VMULVX X17, V22, V22; \
	RSR(V22); \
	VADDVV V15, V16, V23; \
	VMULVX X17, V23, V23; \
	RSR(V23); \
	VADDVV V19, V18, V24; \
	VMULVX X17, V24, i0; \
	RSR(i0); \
	VSUBVV V19, V18, V24; \
	VMULVX X17, V24, i4; \
	RSR(i4); \
	VMULVX X18, V20, V24; \
	VMULVX X19, V21, V25; \
	VADDVV V25, V24, i2; \
	RSR(i2); \
	VMULVX X18, V21, V24; \
	VMULVX X19, V20, V25; \
	VSUBVV V25, V24, i6; \
	RSR(i6); \
	VADDVV V22, V14, V18; \
	VSUBVV V22, V14, V19; \
	VSUBVV V23, V17, V20; \
	VADDVV V23, V17, V21; \
	VMULVX X20, V18, V24; \
	VMULVX X25, V21, V25; \
	VADDVV V25, V24, i1; \
	RSR(i1); \
	VMULVX X23, V19, V24; \
	VMULVX X24, V20, V25; \
	VADDVV V25, V24, i5; \
	RSR(i5); \
	VMULVX X23, V20, V24; \
	VMULVX X24, V19, V25; \
	VSUBVV V25, V24, i3; \
	RSR(i3); \
	VMULVX X20, V21, V24; \
	VMULVX X25, V18, V25; \
	VSUBVV V25, V24, i7; \
	RSR(i7)

#define DCT8CR \
	MOV $5793, X17; \
	MOV $3135, X18; \
	MOV $7568, X19; \
	MOV $1598, X20; \
	MOV $4096, X21; \
	MOV $6811, X23; \
	MOV $4551, X24; \
	MOV $8035, X25

// RECT1R is the round shift by one the 4x8 and 8x4 shift schedules ask for,
// then the rectangular Sqrt2 correction, which reuses cospi32 in X17.
#define RECT1R(v) \
	VADDVX X29, v, v; \
	VSRAVI $1, v, v; \
	VMULVX X17, v, v; \
	VADDVX X28, v, v; \
	VSRAVI $12, v, v

#define RECTCR \
	MOV $1, X29; \
	MOV $2048, X28

// fwdTxfm4x8RVV is the 4x8 DCT_DCT forward transform. There is no lane shuffle
// in RVV, so the transpose is a contiguous store followed by strided loads.
TEXT ·fwdTxfm4x8RVV(SB), NOSPLIT, $128-24
	MOV  res+0(FP), X10
	MOV  src+8(FP), X11
	MOV  srcStride+16(FP), X12
	SLLI $2, X12, X12
	MOV  $4, X13
	VSETVLI X13, E32, M1, TA, MA, X5

	VLE32V (X11), V0
	ADD    X12, X11, X14
	VLE32V (X14), V1
	ADD    X12, X14, X14
	VLE32V (X14), V2
	ADD    X12, X14, X14
	VLE32V (X14), V3
	ADD    X12, X14, X14
	VLE32V (X14), V4
	ADD    X12, X14, X14
	VLE32V (X14), V5
	ADD    X12, X14, X14
	VLE32V (X14), V6
	ADD    X12, X14, X14
	VLE32V (X14), V7
	VSLLVI $2, V0, V0
	VSLLVI $2, V1, V1
	VSLLVI $2, V2, V2
	VSLLVI $2, V3, V3
	VSLLVI $2, V4, V4
	VSLLVI $2, V5, V5
	VSLLVI $2, V6, V6
	VSLLVI $2, V7, V7

	DCT8CR
	FDCT8R(V0, V1, V2, V3, V4, V5, V6, V7)

	MOV    $scratch-128(SP), X14
	VSE32V V0, (X14)
	ADD    $16, X14, X15
	VSE32V V1, (X15)
	ADD    $16, X15, X15
	VSE32V V2, (X15)
	ADD    $16, X15, X15
	VSE32V V3, (X15)
	ADD    $16, X15, X15
	VSE32V V4, (X15)
	ADD    $16, X15, X15
	VSE32V V5, (X15)
	ADD    $16, X15, X15
	VSE32V V6, (X15)
	ADD    $16, X15, X15
	VSE32V V7, (X15)

	MOV $8, X13
	VSETVLI X13, E32, M1, TA, MA, X5
	MOV     $16, X16
	VLSE32V (X14), X16, V0
	ADD     $4, X14, X15
	VLSE32V (X15), X16, V1
	ADD     $4, X15, X15
	VLSE32V (X15), X16, V2
	ADD     $4, X15, X15
	VLSE32V (X15), X16, V3

	FDCT4R(V0, V1, V2, V3)

	RECTCR
	RECT1R(V0)
	RECT1R(V1)
	RECT1R(V2)
	RECT1R(V3)

	VSE32V V0, (X10)
	ADD    $32, X10, X15
	VSE32V V1, (X15)
	ADD    $32, X15, X15
	VSE32V V2, (X15)
	ADD    $32, X15, X15
	VSE32V V3, (X15)
	RET

