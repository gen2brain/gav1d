#define HAD4R(i0, i1, i2, i3, t0, t1, t2, t3) \
	VADDVV i2, i0, t0; \
	VADDVV i3, i1, t1; \
	VSUBVV i2, i0, t2; \
	VSUBVV i3, i1, t3; \
	VADDVV t1, t0, i0; \
	VSUBVV t1, t0, i1; \
